"""Joins the scripts every page loads into three files, so a page makes 5 script requests instead of ~46.

The result is committed (the app has no build step at run time). Run `python scripts/build_static_bundle.py` after
changing any listed script; `./run.sh` does it on start and a core test fails when a bundle is stale.
"""

from __future__ import annotations

from pathlib import Path

STATIC = Path(__file__).resolve().parent.parent / "src" / "static"

# icon_library.js and look_picker.js stay separate tags: they read data attributes off their own <script>.
BUNDLES = {
    "bundle_a.js": ["fast_feel", "phrases", "toast", "app", "pwa"],
    "bundle_b.js": [
        "touch_select", "select_all", "sidebar_tree", "mobile_nav_drawer", "a11y_icon_labels", "icon_buttons", "dynamic_styles",
        "search_field", "modal", "habit_day", "page_header_bar",
    ],
    "bundle_c.js": [
        "async_crud", "inline_edit", "tag_input", "recurrence_picker", "series_scope", "reminders_picker",
        "date_time_fields", "stepper", "dashboard_widget_preview", "avatar_cropper", "upload_zone", "contact_draft",
        "contact_phone_email_rows", "entry_reference_pages", "citation_fields", "entry_fields",
        "label_role_picker", "label_form_picker", "event_format_toggle",
        "holiday_date_sync", "notebook_properties_rows", "notebook_field_options_rows", "notebook_new_note",
        "smart_region", "finance_task_rows", "finance_transaction_form", "calendar_past", "command_palette", "quick_add", "quick_next",
    ],
}


def build() -> dict[str, str]:
    out = {}
    for name, parts in BUNDLES.items():
        chunks = [f"/* generated by scripts/build_static_bundle.py -- edit the source scripts, not this file */\n"]
        for part in parts:
            chunks.append(f"/* {part}.js */\ntry {{\n{(STATIC / (part + '.js')).read_text()}\n}} catch (err) {{ console.error('{part}.js', err); }}\n")
        out[name] = "".join(chunks)
    return out


def main() -> None:
    for name, text in build().items():
        (STATIC / name).write_text(text)


if __name__ == "__main__":
    main()
